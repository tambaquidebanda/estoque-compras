SELECT p.nome AS produto_no_cadastro, p.categoria AS grupo,
       string_agg(v.nome_pdv || ' (id ' || v.icomanda_produto_id || ') R$ ' || v.preco_pdv || ' · ' || v.qtd_30d || ' vendas',
                  '  |  ' ORDER BY v.qtd_30d DESC) AS itens_do_pdv
FROM vendidos v
JOIN pdv_map m ON m.icomanda_produto_id = v.icomanda_produto_id AND m.status = 'mapeado'
JOIN est_produtos p ON p.id = m.produto_id
WHERE coalesce(v.preco_pdv, 0) > 0.02
GROUP BY p.id, p.nome, p.categoria
HAVING count(DISTINCT v.preco_pdv) > 1
ORDER BY p.nome;

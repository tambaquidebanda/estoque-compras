         WHEN m.icomanda_produto_id IS NULL THEN '1 sem vínculo'
         WHEN m.status = 'ignorar' THEN NULL
         WHEN m.status <> 'mapeado' OR m.produto_id IS NULL THEN '2 vínculo pendente'
         WHEN p.id IS NULL THEN '3 produto apagado'
         WHEN NOT p.ativo THEN '4 produto inativo'
         WHEN p.tipo <> 'VENDA' THEN '5 não é de venda'
       END AS situacao,
       v.icomanda_produto_id, v.nome_pdv, v.qtd_30d, v.preco_pdv, v.ultima_venda,
       p.nome AS produto_no_cadastro, p.tipo, p.categoria AS grupo
FROM vendidos v
LEFT JOIN pdv_map m ON m.icomanda_produto_id = v.icomanda_produto_id
LEFT JOIN est_produtos p ON p.id = m.produto_id
WHERE coalesce(v.preco_pdv, 1) > 0.02
  AND (m.icomanda_produto_id IS NULL OR m.status <> 'ignorar')
  AND (m.icomanda_produto_id IS NULL OR m.status <> 'mapeado' OR m.produto_id IS NULL
       OR p.id IS NULL OR NOT p.ativo OR p.tipo <> 'VENDA')
ORDER BY situacao, v.qtd_30d DESC;


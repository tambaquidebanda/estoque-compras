SELECT count(*) AS fora_do_lugar
FROM est_produtos p
JOIN bkp_categoria_20261022 b ON b.id = p.id
WHERE p.nome ~ '^(MP|MC|MU) ' AND COALESCE(p.ativo, true)
  AND p.categoria NOT LIKE 'MP %' AND p.categoria NOT LIKE 'MC %' AND p.categoria NOT LIKE 'MU %';

-- 3b
SELECT categoria, count(*) FROM est_produtos
WHERE nome ~ '^(MP|MC|MU) ' AND COALESCE(ativo, true)
GROUP BY categoria ORDER BY 2 DESC;

